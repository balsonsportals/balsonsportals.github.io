  populateSelect: function(selectId, selectedEmpId) {
    const sel = document.getElementById(selectId);
    if (!sel) return;
    sel.innerHTML = '';
    WORKFORCE_360_DIRECTORY.forEach(e => {
      const opt = document.createElement('option');
      opt.value = e.empId;
      opt.textContent = `${e.empId} • ${e.name} [${e.isInducted ? 'CLEARED' : 'BLOCKED'}]`;
      if (e.empId === selectedEmpId) opt.selected = true;
      sel.appendChild(opt);
    });
  },

